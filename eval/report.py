"""`epv eval`: comparison.jsonl, metrics.json and report.md from committed outputs only.

No model call, no key. Re-running reproduces the files byte for byte (FR-029).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from eval.answers import load_answers
from eval.compare import compare
from eval.metrics import confusion_matrix
from expense_validator.results import load_results


def _metrics(rows: list[dict[str, Any]]) -> dict[str, Any]:
    return {"disposition_confusion": confusion_matrix(rows)}


def _render(metrics: dict[str, Any]) -> str:
    lines = ["# Evaluation report", "", "Generated by `epv eval` from committed outputs.", ""]
    for system, values in metrics["systems"].items():
        cm = values["disposition_confusion"]
        lines += [
            f"## {system}",
            "",
            f"Disposition confusion matrix (rows: answer, columns: prediction), N = {cm['n']}:",
            "",
            "| answer \\ predicted | " + " | ".join(cm["labels"]) + " |",
            "|---|" + "---|" * len(cm["labels"]),
        ]
        for label, row in zip(cm["labels"], cm["matrix"], strict=True):
            lines.append(f"| {label} | " + " | ".join(str(v) for v in row) + " |")
        lines.append("")
    return "\n".join(lines)


def run_eval(
    results_path: Path, out_dir: Path, baselines: dict[str, Path] | None = None
) -> dict[str, Any]:
    answers = load_answers()
    systems: dict[str, list[dict[str, Any]]] = {
        "pipeline": compare(load_results(results_path), answers)
    }
    for name, path in (baselines or {}).items():
        if path.exists():
            systems[name] = compare(load_results(path), answers)
    metrics = {"systems": {name: _metrics(rows) for name, rows in systems.items()}}
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "comparison.jsonl").write_text(
        "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in systems["pipeline"]),
        encoding="utf-8",
    )
    (out_dir / "metrics.json").write_text(
        json.dumps(metrics, indent=2, sort_keys=True, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    (out_dir / "report.md").write_text(_render(metrics) + "\n", encoding="utf-8")
    return metrics

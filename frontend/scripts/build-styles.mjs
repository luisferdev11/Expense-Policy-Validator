// Generates src/styles/tokens.css and src/styles/ledgerline.css from docs/design (read-only).
// The design system's CSS says "every value comes from tokens.css"; this script makes that file.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const design = resolve(root, "..", "docs", "design");
const out = resolve(root, "src", "styles");
mkdirSync(out, { recursive: true });

const tokens = JSON.parse(readFileSync(resolve(design, "tokens.json"), "utf8"));
const light = [];
const dark = [];
for (const t of tokens.color.tokens) {
  light.push(`  --${t.name}: ${t.value.light};`);
  dark.push(`  --${t.name}: ${t.value.dark};`);
}
for (const t of tokens.shadow.tokens) {
  light.push(`  --${t.name}: ${t.value.light};`);
  dark.push(`  --${t.name}: ${t.value.dark};`);
}
const shared = [];
for (const group of [tokens.spacing, tokens.radius, tokens.size]) {
  for (const t of group.tokens) shared.push(`  --${t.name}: ${t.value};`);
}
shared.push(`  --font-sans: ${tokens.type.families.sans};`);
shared.push(`  --font-mono: ${tokens.type.families.mono};`);

const css = `/* Generated by scripts/build-styles.mjs from docs/design/tokens.json. Do not edit. */
:root {
${shared.join("\n")}
${light.join("\n")}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.join("\n")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${dark.join("\n")}
  color-scheme: dark;
}
:root[data-theme="light"] {
${light.join("\n")}
  color-scheme: light;
}
`;
writeFileSync(resolve(out, "tokens.css"), css);
copyFileSync(resolve(design, "ledgerline.css"), resolve(out, "ledgerline.css"));
console.log("styles: tokens.css and ledgerline.css written");
